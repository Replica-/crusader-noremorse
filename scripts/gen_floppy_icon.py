"""Rebuilds src/engine/ui/floppy_icon.hpp from assets/floppy.png.

The picture is a pixel-art floppy disk drawn on a grid of about 31 pixels per
cell: it is cropped to its drawing and sampled at the centre of each cell, giving
the small icon the autosave indicator draws. Usage: python scripts/gen_floppy_icon.py
Needs Pillow.
"""
from pathlib import Path
from PIL import Image

COLUMNS, ROWS = 22, 21
root = Path(__file__).resolve().parent.parent
im = Image.open(root / "assets/floppy.png").convert("RGBA")
x0, y0, x1, y1 = im.getchannel("A").point(lambda v: 255 if v >= 128 else 0).getbbox()
cw, ch = (x1 - x0) / COLUMNS, (y1 - y0) / ROWS

rows = []
for r in range(ROWS):
    row = []
    for c in range(COLUMNS):
        red, green, blue, alpha = im.getpixel((int(x0 + (c + 0.5) * cw), int(y0 + (r + 0.5) * ch)))
        row.append("0x%02X%02X%02X%02X" % (red, green, blue, 255 if alpha >= 128 else 0))
    rows.append("    " + ", ".join(row) + ",")

out = root / "src/engine/ui/floppy_icon.hpp"
out.write_text(
    "#pragma once\n"
    "// Generated by scripts/gen_floppy_icon.py from assets/floppy.png: do not edit.\n"
    "// The autosave indicator, one 0xRRGGBBAA word per pixel (alpha 0 or 255).\n\n"
    "#include <cstdint>\n\n"
    "namespace crusader {\n\n"
    "constexpr int kFloppyWidth = %d, kFloppyHeight = %d;\n"
    "constexpr std::uint32_t kFloppyPixels[kFloppyWidth * kFloppyHeight] = {\n%s\n};\n\n"
    "}  // namespace crusader\n" % (COLUMNS, ROWS, "\n".join(rows)),
    newline="\n",
)
